# write a numpy program to create element-wise operation of 2 given arrays. (==,>,<,>=,<=)

import numpy as np
arr1 = np.array([10,20,30,40])
arr2 = np.array([10,25,30,35])
print(np.equal(arr1,arr2))
print(arr1 == arr2)
print()
print(np.not_equal(arr1,arr2))
print(arr1 != arr2)
print()
print(np.greater(arr1,arr2))
print(arr1 > arr2)
print()
print(np.less(arr1,arr2))
print(arr1 < arr2)
print()
print(np.greater_equal(arr1,arr2))
print(arr1 >= arr2)
print()
print(np.less_equal(arr1,arr2))
print(arr1 <= arr2)
print()